#!/usr/bin/env python3
"""Write a pack DLL's src/fx_ppu.rs: every effect sheet tools/art/densify_fx.py gave dense twins (the effects PPU,
2026-11-09), for its table (league_main / tft hd.rs: EFFECTS, DRAWN_EFFECTS and full_effects() take them all).

    python -I tools/art/fx_ppu_table.py [--pack league|tft] [--check]

A sheet is one when it is under <pack>/effects, carries `hd_idle` beside `idle`, is not one of that hd.rs's own EFFECTS
rows (turrets, Daisy, the sand soldiers ...: dense by their own tools) and every tag of it has its hd_ twin. Its PPU is
read from it: hd_idle's first frame against idle's (2 for densify_fx.py's).
--check: exit 1 when the file would change (CI). With no --pack both packs are written (or checked).
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CRATES = {"league": "league_main", "tft": "tft"}


def paths(pack):
    crate = os.path.join(ROOT, "addons", CRATES[pack], "src")
    return os.path.join(ROOT, pack, "effects"), os.path.join(crate, "hd.rs"), os.path.join(crate, "fx_ppu.rs")


def own_effects(hd_rs, pack):
    hd = open(hd_rs, encoding="utf-8").read()
    i = hd.index("pub const EFFECTS")
    block = hd[i:hd.index("];", i)]
    # the PPU may be written as a quotient (main's league_zaahen_rise: 1.75 / 0.85, 2026-11-11)
    return set(re.findall(rf'\("({pack}_[a-z0-9_]+)", [0-9.]+(?:\s*/\s*[0-9.]+)?, include_str!', block))


def sheets(pack):
    fx, hd_rs, _ = paths(pack)
    own = own_effects(hd_rs, pack)
    out = []
    for fn in sorted(os.listdir(fx)):
        if not fn.endswith("#anim.fanim"):
            continue
        sheet = fn[:-len("#anim.fanim")]
        if sheet in own:
            continue
        anims = json.load(open(os.path.join(fx, fn), encoding="utf-8-sig"))["anims"]
        if "hd_idle" not in anims or "idle" not in anims:
            continue
        plain = [t for t in anims if not t.startswith(("hd_", "lo_"))]
        if any("hd_" + t not in anims for t in plain):
            sys.exit(f"{sheet}: not every tag has its hd_ twin")
        w1 = anims["idle"]["frames"][0]["data"]["w"]
        wd = anims["hd_idle"]["frames"][0]["data"]["w"]
        out.append((sheet, round(wd / w1, 3)))
    return out


def render(pack, rows):
    head = "" if pack == "league" else " --pack tft"
    lines = [f"//! Generated by tools/art/fx_ppu_table.py - do not edit (python -I tools/art/fx_ppu_table.py{head}).",
             "//!",
             "//! The effects PPU (2026-11-09, the user: 「目前完成的所有英雄被反映特效贴图做的非常粗糙 ... 能不能利用PPU来做精致一点」,",
             "//! then 「继续完成别的英雄的技能特效的修复」「另外云顶英雄的也要调啊」): every effect sheet tools/art/densify_fx.py gave",
             "//! dense twins, each tag's hd_ frames read back from Codex's raw drawing (or an older real drawing) at PPU 2 - view",
             "//! effects, buffs and projectiles alike, so hd.rs lists them in EFFECTS, DRAWN_EFFECTS and full_effects() (dense",
             "//! only where the buff and projectile pictures are shrunk too: hd_engine Table::full_effects).",
             "",
             f"/// (sheet, PPU, its .fanim) - {len(rows)} sheets",
             "pub const SHEETS: &[(&str, f32, &str)] = &["]
    for sheet, ppu in rows:
        num = f"{ppu:.1f}" if float(ppu).is_integer() else f"{ppu}"
        lines.append(f'    ("{sheet}", {num}, include_str!("../../../{pack}/effects/{sheet}#anim.fanim")),')
    lines += ["];", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pack", choices=sorted(CRATES))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    bad = False
    for pack in ([a.pack] if a.pack else sorted(CRATES)):
        out = paths(pack)[2]
        text = render(pack, sheets(pack))
        old = open(out, encoding="utf-8").read() if os.path.isfile(out) else None
        if a.check:
            if old != text:
                print(f"{out} is not up to date: python -I tools/art/fx_ppu_table.py --pack {pack}")
                bad = True
            else:
                print(f"{pack}: fx_ppu.rs up to date")
            continue
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {out}: {text.count('include_str!')} sheets")
    if bad:
        sys.exit(1)


if __name__ == "__main__":
    main()
