#!/usr/bin/env python3
"""Write addons/game_places/src/sigs.rs: the patterns league.dll and the whole-body add-ons find their places by at
run time (game_places::resolve), made from the build addons/league_main/src/build.rs lists.

    python -I tools/re/make_sigs.py [--exe <TeamfightManager2.exe>]

The same steps tools/re/find_build.py runs offline with a disassembler, cut down to what plain byte searches can do in
the game: every pattern here has its calls / jumps out of it and its rip-relative displacements wildcarded (capstone
decides which bytes those are, here, once), and the layouts (where a call's size asks sit after it) are byte offsets
with the exact bytes read from the listed build. When a game update keeps these shapes - 0.6.3 -> 0.6.4 kept all of
them but the UI drawers' spacing - league.dll and the add-ons find the new places by themselves; when it does not,
they draw 1x frames as before and find_build.py (a human in the loop) finds them, and this script is run again on
the new build.rs. The EXE is only read to check every pattern finds exactly the listed place.
Needs `pip install capstone pefile`.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import find_build as fb  # noqa: E402

OUT = os.path.join(fb.ROOT, "addons", "game_places", "src", "sigs.rs")


def pattern(code, rva):
    """(bytes, mask) with the wildcarded bytes masked out (mask 0)."""
    rx = fb.wildcard(code, rva)
    mask, i = [], 0
    # fb.wildcard escapes every literal byte and writes b"." for a wildcard: walk the regex back
    while i < len(rx):
        if rx[i:i + 1] == b".":
            mask.append(0)
            i += 1
        elif rx[i:i + 1] == b"\\":
            mask.append(1)
            i += 2
        else:
            mask.append(1)
            i += 1
    assert len(mask) == len(code), (len(mask), len(code))
    return bytes(c if m else 0 for c, m in zip(code, mask)), bytes(mask)


def rs_bytes(bs, ind=8, per=16):
    return "\n".join(" " * ind + ", ".join(f"0x{c:02x}" for c in bs[k:k + per]) + "," for k in range(0, len(bs), per))


def rs_pattern(name, doc, code, rva):
    b, m = pattern(code, rva)
    return (f"/// {doc}\npub const {name}: Pattern = Pattern {{\n    bytes: &[\n{rs_bytes(b)}\n    ],\n"
            f"    mask: &[\n{rs_bytes(m)}\n    ],\n}};\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", default=fb.GAME)
    a = ap.parse_args()
    b = fb.old_build()
    sig = b["sigs"]
    e = fb.Exe(a.exe)
    if not all(e.read(r, len(x)) == x for r, x in sig.items()):
        sys.exit("this EXE is not the build build.rs lists: the patterns are made from that build")
    hash_call = next(i.address - b["anim"] for i in e.md.disasm(sig[b["anim"]], b["anim"])
                     if i.mnemonic == "call" and i.operands[0].imm == b["hash"])
    old_call = b["battle_anim_ret"][0] - 5
    battle_asks = [(r - len(x) - old_call, x) for r in b["battle_size_ret"][:2] for n in (2, 3)
                   if (x := sig.get(r - n)) is not None]
    body_asks_old = [(r, next(sig[r - n] for n in (2, 3) if r - n in sig)) for r in b["battle_size_ret"][2:]]
    first = body_asks_old[0][0] - len(body_asks_old[0][1])
    body_asks = [(r - len(x) - first, x) for r, x in body_asks_old]
    ui = []
    for k, ret in enumerate(b["ui_anim_ret"]):
        call = ret - 5
        asks = b["ui_size_ret"][4 * k:4 * k + 4]
        ui.append((call, [r - ret for r in asks]))
    src = open(fb.BUILD_RS, encoding="utf-8").read()
    sized_rets = [int(x, 16) for x in re.findall(r"0x[0-9a-f]+", re.search(r"ui_sized_anim_ret: &\[([^\]]*)\]",
                                                                             src).group(1))]
    sized = [b["ui_anim_ret"].index(r) for r in sized_rets]
    # the entity render: the listed build's call of the body draw; the UI drawers inside the same function (the
    # scoreboard portraits) are looked for there at run time (0.6.4 -> 0.6.5 their asks moved by 3 and every drawer
    # moved apart from the others)
    render_call = next(r for r, x in sig.items() if len(x) == 5 and x[0] == 0xe8
                       and r + 5 + int.from_bytes(x[1:], "little", signed=True) == b["body_draw"])
    render_fn = e.func_of(render_call)
    in_render = [k for k, (call, _) in enumerate(ui) if e.func_of(call) == render_fn]

    out = ["//! Generated by tools/re/make_sigs.py from addons/league_main/src/build.rs's build "
           f"({b['name']}) - do not edit.",
           "//! The patterns' wildcarded bytes are its calls / jumps out and rip-relative displacements (capstone's call,",
           "//! made offline); the layouts are byte offsets with the exact bytes of that build.",
           "",
           "use crate::Pattern;",
           "",
           f"/// The build these were made from.\npub const FROM: &str = \"{b['name']}\";",
           f"/// The rvas of that build (the fast path checks them first, by the patterns).",
           f"pub const OLD_ANIM: usize = {b['anim']:#x};",
           f"pub const OLD_DISPLAY_FN: usize = {b['display_fn']:#x};",
           f"pub const OLD_DISPLAY_SLOT: usize = {b['display_slot']:#x};",
           "",
           rs_pattern("ANIM", "The anim-table lookup's head (33 HashMap<String, _>::get share it): the sheet lookup too.",
                      sig[b["anim"]], b["anim"]),
           f"/// Where the lookup head calls the hash.\npub const HASH_CALL: usize = {hash_call:#x};\n",
           rs_pattern("HASH", "The anim tables' hash's head.", sig[b["hash"]], b["hash"]),
           rs_pattern("DISPLAY", "The display-update handler's head.", sig[b["display_fn"]], b["display_fn"]),
           "/// The battlefield frame lookup: its two size asks after its call of the anim lookup (offset from the call, bytes).",
           "pub const BATTLE_ASKS: &[(usize, &[u8])] = &[" + ", ".join(
               f"({d:#x}, &[{', '.join(f'0x{c:02x}' for c in x)}])" for d, x in battle_asks) + "];",
           "/// The body draw's four size asks (offset from the first, bytes).",
           "pub const BODY_ASKS: &[(usize, &[u8])] = &[" + ", ".join(
               f"({d:#x}, &[{', '.join(f'0x{c:02x}' for c in x)}])" for d, x in body_asks) + "];",
           "/// The UI drawers (encyclopedia / face icons, pick slot, BP grid, pick moment, scoreboard portraits): the old call",
           "/// of the anim lookup and its four size asks' return addresses relative to the call's return address.",
           "pub const UI: &[(usize, [usize; 4])] = &[" + ", ".join(
               f"({c:#x}, [{', '.join(f'{d:#x}' for d in ds)}])" for c, ds in ui) + "];",
           "/// Which of them draw the whole body (take the UI sizes).",
           f"pub const UI_SIZED: &[usize] = &{sized};",
           "/// Which of them sit inside the entity render (the function calling the body draw).",
           f"pub const UI_IN_RENDER: &[usize] = &{in_render};",
           "/// grow_one of the 0xd0-byte draw commands writes this inside its first 0x40 bytes.",
           "pub const GROW_MARK: &[u8] = &[0x48, 0xc7, 0x44, 0x24, 0x28, 0xd0, 0x00, 0x00, 0x00];",
           "/// The hooks' functions start with this 12-byte prologue and `sub rsp, imm32`.",
           f"pub const PROLOGUE: &[u8] = &[{', '.join(f'0x{c:02x}' for c in fb.PROLOGUE)}, 0x48, 0x81, 0xec];",
           ""]
    text = "\n".join(out)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    # each pattern finds exactly its place in this EXE
    for name, rva in (("anim", b["anim"]), ("hash", b["hash"]), ("display_fn", b["display_fn"])):
        hits = e.find(fb.wildcard(sig[rva], rva))
        print(f"{name}: {len(hits)} hits, the listed one among them: {rva in hits}")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
