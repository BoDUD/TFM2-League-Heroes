#!/usr/bin/env python3
"""league_lucian's R (The Culling) fired while he moves.

    python tools/kit/lucian_r_move.py [--check]

The user, 2026-10-21: 「卢锡安的大招能不能加强一下 改成移动时也可以释放 不然这个大招经常硬控自己几秒」. The ult was one
186-tick action that cannot be cancelled (CasterAnimation `ult` 182 ticks on top), so he stood still for three seconds.
League lets him walk while the shots fly. Here the action keeps only the draw (R_DUR ticks, the first shot's moment);
the shots are `Delayed` effects already scheduled by the cast, so they go on firing - from wherever he is at each shot,
at the nearest enemy champion as before - while the AI walks him and attacks. Crowd control still ends them (the
`AllyChampionInCC` check before each shot), and so does his death (the `AllyOnlySelf` one). The picture: his own
animations while he moves (the 182-tick `CasterAnimation` would slide him along in the shooting pose); the cast plays
the ult strip for the draw. (No wall stops a projectile in this game, so the shots already go through walls.)
Idempotent. Kits without a build script (league_lucian is one) are patched in place; league_sylas's copy of his ult
is regenerated by its make_override.py.
"""
import argparse
import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PATH = os.path.join(os.path.dirname(HERE), "..", "league", "champion", "league_lucian.data_champion")
PATH = os.path.normpath(os.path.join(HERE, "..", "..", "league", "champion", "league_lucian.data_champion"))
R_DUR = 12                     # the draw: the first shot leaves on tick 9


def strip_anim(o):
    """Every CasterAnimation `ult` / RemoveCasterAnimation `ult` out of the tree; -> how many."""
    n = 0
    if isinstance(o, dict):
        for k, v in list(o.items()):
            if isinstance(v, list):
                keep = []
                for x in v:
                    if isinstance(x, dict) and x.get("type") in ("CasterAnimation", "RemoveCasterAnimation") \
                            and x.get("name") == "ult":
                        n += 1
                    else:
                        keep.append(x)
                o[k] = keep
            n += strip_anim(o[k])
    elif isinstance(o, list):
        for x in o:
            n += strip_anim(x)
    return n


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    kit = json.loads(io.open(PATH, encoding="utf-8-sig").read())
    u = kit["ult"]
    before = u["duration"]
    n = strip_anim(u["effect"])
    u["duration"] = R_DUR
    print(f"ult duration {before} -> {R_DUR}, {n} ult animation nodes taken out")
    if not a.check:
        io.open(PATH, "w", encoding="utf-8", newline="").write(
            json.dumps(kit, ensure_ascii=False, indent=2).replace("\n", "\r\n") + "\r\n")


if __name__ == "__main__":
    main()
