#[cfg(test)]
mod tests {
    use super::*;

    /// 一段字里的数（`12`、`1.5`），排好序。
    fn numbers(s: &str) -> Vec<String> {
        let mut out = Vec::new();
        let mut cur = String::new();
        for c in s.chars() {
            if c.is_ascii_digit() || (c == '.' && !cur.is_empty()) {
                cur.push(c);
            } else if !cur.is_empty() {
                out.push(cur.trim_end_matches('.').to_string());
                cur.clear();
            }
        }
        if !cur.is_empty() {
            out.push(cur.trim_end_matches('.').to_string());
        }
        out.sort();
        out
    }

    #[test]
    fn every_augment_has_korean_and_japanese_with_the_same_numbers() {
        assert_eq!(KJ.len(), AUGS.len());
        for (i, a) in AUGS.iter().enumerate() {
            let k = of(i).unwrap_or_else(|| panic!("{}: no Korean / Japanese", a.key));
            assert_eq!(KJ.iter().filter(|x| x.key == a.key).count(), 1, "{}", a.key);
            let want = numbers(a.desc[0]);
            for (lang, [name, desc]) in [("ko", k.ko), ("ja", k.ja)] {
                assert!(!name.trim().is_empty() && !desc.trim().is_empty(), "{} {lang}", a.key);
                assert_eq!(numbers(desc), want, "{} {lang}: {desc}", a.key);
            }
            // the Korean is Korean (hangul); the Japanese is kana or kanji, never English (攻撃力 +20% has no kana)
            assert!(k.ko[1].chars().any(|c| ('\u{ac00}'..='\u{d7a3}').contains(&c)), "{}", a.key);
            assert!(k.ja[1].chars().any(|c| c >= '\u{3040}' && !('\u{ac00}'..='\u{d7a3}').contains(&c)), "{}", a.key);
        }
        assert_eq!(numbers("+12.5% 和 3 秒。"), vec!["12.5", "3"]);
    }
}
